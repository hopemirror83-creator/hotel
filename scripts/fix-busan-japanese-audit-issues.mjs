import { readFile, writeFile } from 'node:fs/promises';

const contentPath = 'data/multilingual-myeongdong-content.json';
const modulePath = 'src/data/multilingualHotels.ts';
const content = JSON.parse(await readFile(contentPath, 'utf8'));

const replacements = [
  ['一報できます', '一望できます'],
  ['ブランド의 信頼感', 'ブランドの信頼感'],
  ['和洋中', '韓国料理・洋食・中華'],
  ['釜山港国際旅客ターミナルへのアクセスも良く、船で釜山を訪れる旅行者にとっても便利な拠点となります', '釜山駅を起点に市内各地へ移動したい旅行者にとって、使いやすい拠点となります'],
  ['到着が遅い場合、何を確認すべきですか。', '金海国際空港からのアクセス方法を教えてください。']
];

let serialized = JSON.stringify(content);
for (const [from, to] of replacements) {
  const count = serialized.split(from).length - 1;
  serialized = serialized.split(from).join(to);
  console.log(`${from} -> ${to}: ${count}`);
}

const corrected = JSON.parse(serialized);
const ramadaFaq = corrected['busan-9079659'].ja.faqs.find((faq) => faq.question.includes('金海国際空港'));
if (!ramadaFaq) throw new Error('Ramada airport FAQ was not found.');
ramadaFaq.question = '到着が遅い場合、何を確認すべきですか。';
ramadaFaq.answer = '到着が遅い場合は、フロントの受付時間と釜山駅からホテルまでの動線を事前に確認してください。深夜は利用できる交通手段が限られる可能性があるため、予約条件と到着方法をあわせて確認すると安心です。';
await writeFile(contentPath, `${JSON.stringify(corrected, null, 2)}\n`, 'utf8');
await writeFile(modulePath, `// Generated by scripts/generate-multilingual-hotel-pilot.mjs\nexport const multilingualHotels = ${JSON.stringify(corrected, null, 2)} as const;\n`, 'utf8');
console.log('Corrected audited Japanese issues for Busan pages.');
