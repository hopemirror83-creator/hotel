import { readFile, writeFile } from 'node:fs/promises';

const jsonPath = 'data/multilingual-myeongdong-content.json';
const modulePath = 'src/data/multilingualHotels.ts';
const content = JSON.parse(await readFile(jsonPath, 'utf8'));
const fixes = [
  ['seoul-1620721', 'Agoda의', 'Agodaの'],
  ['seoul-1974802', '朝食의提供', '朝食の提供'],
  ['seoul-699258', 'アクセスの良です', 'アクセスの良さです'],
  ['seoul-12448894', '和洋韓のメニュー', '韓国料理と洋食のメニュー'],
  ['seoul-764629', 'お弁当（デリバリースタイル）', 'お弁当形式']
];

for (const [slug, from, to] of fixes) {
  const serialized = JSON.stringify(content[slug].ja);
  if (!serialized.includes(from)) throw new Error(`Expected phrase not found: ${slug} / ${from}`);
  content[slug].ja = JSON.parse(serialized.split(from).join(to));
  console.log(`Fixed ${slug}: ${from} -> ${to}`);
}

await writeFile(jsonPath, `${JSON.stringify(content, null, 2)}\n`, 'utf8');
await writeFile(modulePath, `// Generated by scripts/generate-multilingual-hotel-pilot.mjs\nexport const multilingualHotels = ${JSON.stringify(content, null, 2)} as const;\n`, 'utf8');
