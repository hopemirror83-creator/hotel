import { readFile, writeFile } from 'node:fs/promises';

const contentPath = 'data/multilingual-myeongdong-content.json';
const modulePath = 'src/data/multilingualHotels.ts';
const content = JSON.parse(await readFile(contentPath, 'utf8'));

content['incheon-3155645'].ja.address = '仁川広域市 永宗区 新都市南路142番キル 6';
content['incheon-50405896'].ja.address = '仁川広域市 永宗区 ヒンバウィ路59番キル 8';

await writeFile(contentPath, `${JSON.stringify(content, null, 2)}\n`, 'utf8');
await writeFile(modulePath, `// Generated by scripts/generate-multilingual-hotel-pilot.mjs\nexport const multilingualHotels = ${JSON.stringify(content, null, 2)} as const;\n`, 'utf8');
console.log('Corrected two Japanese Incheon Airport addresses.');
