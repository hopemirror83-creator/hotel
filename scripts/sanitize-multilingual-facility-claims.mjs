import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const file = path.join(root, 'src', 'data', 'multilingualHotels.ts');
const apply = process.argv.includes('--apply');
const source = await readFile(file, 'utf8');
const match = source.match(/export const multilingualHotels\s*=\s*([\s\S]*?)\s+as const;?\s*$/)
  || source.match(/export const multilingualHotels\s*=\s*([\s\S]*);\s*$/);
if (!match) throw new Error('Could not parse multilingualHotels.ts');

const hotels = JSON.parse(match[1]);
const report = { hotels: Object.keys(hotels).length, english: 0, japanese: 0 };

for (const localized of Object.values(hotels)) {
  for (const [language, content] of Object.entries(localized)) {
    localized[language] = walk(content, language, '');
  }
}

if (apply) {
  await writeFile(
    file,
    `// Generated by scripts/generate-multilingual-hotel-pilot.mjs\nexport const multilingualHotels = ${JSON.stringify(hotels, null, 2)};\n`,
    'utf8'
  );
}

console.log(JSON.stringify({ mode: apply ? 'apply' : 'audit', ...report }, null, 2));

function walk(value, language, key) {
  if (typeof value === 'string') return neutralize(value, language, key);
  if (Array.isArray(value)) return [...new Set(value.map((item) => JSON.stringify(walk(item, language, key))))].map(JSON.parse);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value).map(([childKey, child]) => [childKey, walk(child, language, childKey)]));
}

function neutralize(value, language, key) {
  const englishWifi = /(?:wi-?fi|wireless internet).{0,80}(?:not provided|not available|unavailable|not included|no wi-?fi)|(?:no|without).{0,30}(?:wi-?fi|wireless internet)/i;
  const englishBreakfast = /breakfast.{0,100}(?:not provided|not available|unavailable|not included|isn't included|is not included)|(?:no|without).{0,35}breakfast/i;
  const japaneseWifi = /(?:Wi-?Fi|ワイファイ).{0,60}(?:提供されない|利用できない|ありません|含まれていない|ない)/i;
  const japaneseBreakfast = /朝食.{0,80}(?:提供されない|ありません|含まれていない|含まれず|ない)/i;

  const wifi = language === 'ja' ? japaneseWifi.test(value) : englishWifi.test(value);
  const breakfast = language === 'ja' ? japaneseBreakfast.test(value) : englishBreakfast.test(value);
  if (!wifi && !breakfast) return value;
  if (language === 'ja') {
    report.japanese += 1;
    if (key === 'question') return breakfast ? '朝食の営業と宿泊プランへの含有条件はどこで確認できますか？' : 'Wi-Fiの提供範囲と利用条件はどこで確認できますか？';
    if (wifi && breakfast) return '朝食とWi-Fiの条件は宿泊プランや利用日によって異なるため、予約画面またはホテルへ最新情報をご確認ください。';
    if (breakfast) return '朝食の営業状況と宿泊プランへの含有条件は、予約画面またはホテルへ最新情報をご確認ください。';
    return 'Wi-Fiの提供範囲と利用条件は、予約画面またはホテルへ最新情報をご確認ください。';
  }

  report.english += 1;
  if (key === 'question') return breakfast ? 'How can I confirm breakfast service and whether it is included in my rate?' : 'How can I confirm Wi-Fi availability and usage conditions?';
  if (wifi && breakfast) return 'Breakfast and Wi-Fi conditions can vary by room plan and stay date, so confirm the latest details on the booking page or with the hotel.';
  if (breakfast) return 'Breakfast operation and rate-inclusion conditions can vary, so confirm the latest details on the booking page or with the hotel.';
  return 'Wi-Fi availability and usage conditions should be confirmed on the booking page or directly with the hotel.';
}
